-- Run once in the Supabase SQL Editor before enabling V2 Messages.
-- The contact directory contains only user IDs, usernames, display names,
-- and engineer status. Authenticated users can read it but cannot write it.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists public.message_directory (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text,
  is_engineer boolean not null default false
);

alter table public.message_directory enable row level security;
revoke all on public.message_directory from anon, authenticated;
grant select on public.message_directory to authenticated;

drop policy if exists message_directory_authenticated_read on public.message_directory;
create policy message_directory_authenticated_read on public.message_directory
  for select to authenticated
  using ((select auth.uid()) is not null);

create or replace function private.sync_message_directory()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    delete from public.message_directory where id = old.id;
    return old;
  end if;

  if coalesce(new.blocked, false) then
    delete from public.message_directory where id = new.id;
    return new;
  end if;

  insert into public.message_directory (id, username, display_name, is_engineer)
  values (new.id, new.username, new.display_name, coalesce(new.is_engineer, false))
  on conflict (id) do update set
    username = excluded.username,
    display_name = excluded.display_name,
    is_engineer = excluded.is_engineer;
  return new;
end;
$$;
revoke all on function private.sync_message_directory() from public, anon, authenticated;

drop trigger if exists profiles_sync_message_directory on public.profiles;
create trigger profiles_sync_message_directory
  after insert or update or delete on public.profiles
  for each row execute function private.sync_message_directory();

insert into public.message_directory (id, username, display_name, is_engineer)
select p.id, p.username, p.display_name, coalesce(p.is_engineer, false)
from public.profiles as p
where not coalesce(p.blocked, false)
on conflict (id) do update set
  username = excluded.username,
  display_name = excluded.display_name,
  is_engineer = excluded.is_engineer;

drop function if exists public.message_contacts();

create table if not exists public.app_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  check (sender_id <> recipient_id)
);

alter table public.app_messages enable row level security;
create index if not exists app_messages_sender_created_idx on public.app_messages (sender_id, created_at);
create index if not exists app_messages_recipient_created_idx on public.app_messages (recipient_id, created_at);
revoke all on public.app_messages from anon;
grant select, insert on public.app_messages to authenticated;
grant update (read_at) on public.app_messages to authenticated;
grant usage, select on sequence public.app_messages_id_seq to authenticated;

drop policy if exists app_messages_read_participant on public.app_messages;
create policy app_messages_read_participant on public.app_messages
  for select to authenticated
  using ((select auth.uid()) = sender_id or (select auth.uid()) = recipient_id);

drop policy if exists app_messages_send_as_self on public.app_messages;
create policy app_messages_send_as_self on public.app_messages
  for insert to authenticated
  with check ((select auth.uid()) = sender_id and (select auth.uid()) <> recipient_id);

drop policy if exists app_messages_mark_received on public.app_messages;
create policy app_messages_mark_received on public.app_messages
  for update to authenticated
  using ((select auth.uid()) = recipient_id)
  with check ((select auth.uid()) = recipient_id);